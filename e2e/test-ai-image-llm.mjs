import { start, check, newPage, failed } from './editor-lib.mjs';
import { BASE } from './lib.mjs';

const { browser, page } = await start();
try {
  console.log('1. Creating new test page...');
  await newPage(page, 'AI Image LLM Test Page');
  await page.waitForTimeout(500);

  // Focus the first empty block
  const firstBlock = page.locator('.lit-page-content [data-content-editable-leaf="true"]').first();
  await firstBlock.click();
  await page.waitForTimeout(200);

  console.log('2. Testing Slash command "AI 이미지"...');
  await page.keyboard.type('/ai image');
  await page.waitForTimeout(300);

  const slashOption = page.locator('.nc-slash-menu [role="option"]').filter({ hasText: /AI Image|AI 이미지/ }).first();
  await slashOption.waitFor({ state: 'visible', timeout: 5000 });
  check('Slash menu option for AI Image appears', await slashOption.isVisible());

  await slashOption.click();
  await page.waitForTimeout(400);

  // Verify AI Image popover is visible
  const popover = page.locator('.nc-media-picker [data-testid="ai-image-tab"]');
  await popover.waitFor({ state: 'visible', timeout: 5000 });
  check('AI Image generation popover opened without plan restrictions', await popover.isVisible());

  // Check no plan blocking toast
  const planToast = page.locator('.nc-toast:has-text("Business and Enterprise")');
  check('No plan upsell toast appeared', (await planToast.count()) === 0);

  console.log('3. Requesting image generation with current LLM...');
  const textarea = popover.locator('textarea');
  await textarea.fill('Blue futuristic robot');
  await page.waitForTimeout(200);

  const genBtn = popover.locator('button.nc-blk-btn.primary');
  await genBtn.click();

  // Wait for image to generate and popover to close
  await popover.waitFor({ state: 'hidden', timeout: 30000 });
  check('AI Image popover closed after generation', !(await popover.isVisible()));

  // Wait for the image block to be filled
  const imgBlock = page.locator('.lit-page-content img.nc-image');
  await imgBlock.waitFor({ state: 'visible', timeout: 30000 });
  const src = await imgBlock.getAttribute('src');
  console.log('Generated image src:', src);
  check('Image block is populated with generated image URL', !!src && src.startsWith('/files/'));

  console.log('4. Testing Text Selection -> "AI 이미지"...');
  // Add a text block at the bottom
  const appendEl = page.locator('.nc-click-to-append').first();
  await appendEl.scrollIntoViewIfNeeded().catch(() => {});
  const appendBox = await appendEl.boundingBox();
  if (appendBox) {
    await page.mouse.click(appendBox.x + 120, appendBox.y + 24);
  } else {
    await page.locator('.lit-page-content').click({ position: { x: 200, y: 700 } }).catch(() => {});
  }
  await page.waitForTimeout(300);
  await page.keyboard.type('High-speed fiber optic switch');
  await page.waitForTimeout(300);

  // Select the text and right-click to trigger TextActionMenu
  const leaf = page.locator('.lit-page-content [data-content-editable-leaf="true"]').last();
  await leaf.waitFor({ state: 'visible', timeout: 5000 });
  const box = await leaf.boundingBox();
  if (box) {
    await leaf.dblclick();
    await page.waitForTimeout(200);
    await page.mouse.click(box.x + 30, box.y + 10, { button: 'right' });
    await page.waitForTimeout(400);

    const tamMenu = page.locator('.lit-text-action-menu');
    await tamMenu.waitFor({ state: 'visible', timeout: 5000 });
    check('Text action menu opened on right-click', await tamMenu.isVisible());

    const aiImgSkill = tamMenu.locator('.nc-tam-skill').filter({ hasText: 'AI 이미지' }).first();
    check('AI 이미지 option is present in text action menu', await aiImgSkill.isVisible());

    console.log('5. Clicking AI 이미지 in TextActionMenu...');
    await aiImgSkill.click();

    // Wait for the second image block to be generated by the LLM
    const secondImg = page.locator('.lit-page-content img.nc-image').nth(1);
    await secondImg.waitFor({ state: 'visible', timeout: 35000 });
    const secondSrc = await secondImg.getAttribute('src');
    console.log('Second generated image src:', secondSrc);
    check('New image block created from text selection with current LLM', !!secondSrc && secondSrc.startsWith('/files/'));
  }

  console.log('All AI image LLM generation tests completed successfully!');
} catch (err) {
  console.error('Test error:', err);
  process.exitCode = 1;
} finally {
  await browser.close();
}

if (failed > 0) {
  process.exit(1);
}
